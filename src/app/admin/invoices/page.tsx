import type { Metadata } from "next";
import Link from "next/link";
import { ExternalLink, FileText, Receipt } from "lucide-react";
import { PageHeader } from "@/components/app-shell/page-header";
import { ListToolbar } from "@/components/common/list-toolbar";
import { PaginationBar } from "@/components/common/pagination-bar";
import { EmptyState } from "@/components/common/empty-state";
import { StatusBadge } from "@/components/common/status-badge";
import { LocalTime } from "@/components/common/local-time";
import { requireAdmin } from "@/lib/auth/guards";
import { parseListParams } from "@/lib/list-params";
import { listDocuments } from "@/lib/services/billing/queries";
import { formatMoney } from "@/lib/format";

export const instant = false;

export const metadata: Metadata = { title: "Invoices & receipts" };

export default async function InvoicesPage({ searchParams }: PageProps<"/admin/invoices">) {
  await requireAdmin("/admin/invoices");
  const raw = await searchParams;
  const params = parseListParams(raw, { filterKeys: ["type", "issuer", "status"], defaultDir: "desc" });
  const { rows, total } = await listDocuments(params);

  return (
    <>
      <PageHeader
        title="Invoices & receipts"
        description="Every billing document: Whop's own receipts, Foremint-branded receipts generated from verified Whop payments, and credit notes for refunds."
      />
      <ListToolbar
        searchPlaceholder="Document number"
        filters={[
          {
            key: "type",
            label: "Types",
            options: [
              { value: "receipt", label: "Receipts" },
              { value: "credit_note", label: "Credit notes" },
              { value: "invoice", label: "Invoices" },
            ],
          },
          {
            key: "issuer",
            label: "Issuers",
            options: [
              { value: "foremint", label: "Foremint" },
              { value: "whop", label: "Whop" },
            ],
          },
          {
            key: "status",
            label: "Statuses",
            options: [
              { value: "paid", label: "Paid" },
              { value: "issued", label: "Issued" },
              { value: "refunded", label: "Refunded" },
              { value: "void", label: "Void" },
            ],
          },
        ]}
      />
      {rows.length === 0 ? (
        <EmptyState icon={Receipt} title="No documents found" description="Receipts are created automatically when a payment is confirmed." />
      ) : (
        <div className="overflow-x-auto rounded-2xl border bg-card">
          <table className="w-full min-w-[820px] text-sm">
            <thead className="bg-muted/50 text-left text-xs text-muted-foreground">
              <tr>
                <th className="px-4 py-3 font-medium">Number</th>
                <th className="px-4 py-3 font-medium">Issued</th>
                <th className="px-4 py-3 font-medium">Customer</th>
                <th className="px-4 py-3 font-medium">Type</th>
                <th className="px-4 py-3 text-right font-medium">Amount</th>
                <th className="px-4 py-3 font-medium">Status</th>
                <th className="px-4 py-3" />
              </tr>
            </thead>
            <tbody className="divide-y">
              {rows.map((d) => (
                <tr key={d.id}>
                  <td className="px-4 py-3 font-mono text-xs font-medium">{d.number}</td>
                  <td className="px-4 py-3 whitespace-nowrap">
                    <LocalTime value={d.issued_at} format="date" />
                  </td>
                  <td className="px-4 py-3">
                    <p>{d.customerName || "—"}</p>
                    <p className="text-xs text-muted-foreground">{d.customerEmail}</p>
                  </td>
                  <td className="px-4 py-3">
                    {d.document_type === "credit_note" ? "Credit note" : d.document_type === "invoice" ? "Invoice" : "Receipt"}
                    <span className="block text-xs text-muted-foreground">{d.issuer === "whop" ? "Issued by Whop" : "Generated by Foremint"}</span>
                  </td>
                  <td className="px-4 py-3 text-right tabular-nums">{formatMoney(d.total_cents, d.currency)}</td>
                  <td className="px-4 py-3">
                    <StatusBadge status={d.status} />
                  </td>
                  <td className="px-4 py-3 text-right">
                    <div className="flex items-center justify-end gap-3">
                      {d.transaction_id ? (
                        <Link href={`/admin/payments/${d.transaction_id}`} className="text-sm text-muted-foreground hover:text-foreground">
                          Payment
                        </Link>
                      ) : null}
                      <a href={`/api/billing/documents/${d.id}/pdf`} target="_blank" rel="noopener" className="inline-flex items-center gap-1 text-sm font-medium text-primary hover:underline">
                        {d.issuer === "whop" ? <ExternalLink className="size-3.5" aria-hidden /> : <FileText className="size-3.5" aria-hidden />}
                        Open
                      </a>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      <PaginationBar basePath="/admin/invoices" searchParams={raw} page={params.page} pageSize={params.pageSize} total={total} />
    </>
  );
}
