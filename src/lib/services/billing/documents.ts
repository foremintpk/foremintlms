import "server-only";
import { createAdminClient } from "@/lib/supabase/admin";
import { getPublicSettings, getSetting } from "@/lib/settings";
import { documentNumber } from "@/lib/domain/billing";
import { billingPeriodLabel } from "@/lib/format";
import type { Database, Json } from "@/types/database";
import { paymentsRpc } from "@/lib/services/payments/rpc";
import {
  addressLines,
  buildReceiptSnapshot,
  splitAddress,
  toReceiptLines,
  type ReceiptSeller,
  type ReceiptSnapshot,
  type WhopLineLike,
} from "./receipt-model";
import type { BillingDocumentRow, PaymentTransactionRow, PlanRow, ProductRow } from "@/lib/services/payments/types";

/**
 * Billing documents for a payment:
 * - a pointer to Whop's own receipt (issuer "whop"), fetched as a PDF from
 *   Whop on demand;
 * - a Foremint-branded receipt (issuer "foremint") generated from the
 *   verified Whop payment data and frozen at issue time;
 * - a Foremint credit note once anything is refunded.
 * Every insert is idempotent (unique per transaction + issuer + type).
 */

export interface PaymentFacts {
  whopPaymentId: string;
  whopMembershipId: string | null;
  paidAt: string | null;
  currency: string;
  status: string;
  lineItems: WhopLineLike[] | null;
  discountCents: number;
  taxCents: number | null;
  taxBehavior: string | null;
  totalCents: number;
  refundedCents: number;
  promoCodeId: string | null;
  paymentMethod: string | null;
  billingAddress: Record<string, string | null> | null;
  customerEmail: string | null;
}

export async function getReceiptSeller(): Promise<ReceiptSeller> {
  const [settings, taxId, footer] = await Promise.all([
    getPublicSettings(),
    getSetting<string>("legal.tax_id", ""),
    getSetting<string>("billing.invoice_footer", ""),
  ]);
  return {
    brandName: settings.brandName,
    legalEntityName: settings.legalEntityName || null,
    addressLines: splitAddress(settings.businessAddress),
    registrationNumber: settings.registrationNumber || null,
    taxId: taxId || null,
    supportEmail: settings.supportEmail || null,
    footer: footer || null,
  };
}

async function nextNumber(kind: "receipt" | "credit_note", issuedAt: Date): Promise<string> {
  const { data, error } = await paymentsRpc("next_billing_document_number");
  if (error || data === null || data === undefined) throw new Error(`document number failed: ${error?.message}`);
  return documentNumber(kind, Number(data), issuedAt);
}

async function customerFor(userId: string | null, facts: PaymentFacts) {
  const admin = createAdminClient();
  let name: string | null = facts.billingAddress?.name ?? null;
  let email: string | null = facts.customerEmail;
  if (userId) {
    const [profile, priv] = await Promise.all([
      admin.from("profiles").select("full_name").eq("id", userId).maybeSingle(),
      admin.from("profile_private").select("email, billing_name").eq("user_id", userId).maybeSingle(),
    ]);
    name = priv.data?.billing_name || name || profile.data?.full_name || null;
    email = priv.data?.email ?? email;
  }
  return { name, email, addressLines: addressLines(facts.billingAddress) };
}

async function findDocument(transactionId: string, issuer: "whop" | "foremint", type: "receipt" | "credit_note") {
  const { data } = await createAdminClient()
    .from("billing_documents")
    .select("*")
    .eq("transaction_id", transactionId)
    .eq("issuer", issuer)
    .eq("document_type", type)
    .maybeSingle();
  return (data as BillingDocumentRow | null) ?? null;
}

async function insertIgnoringDuplicate(row: Database["public"]["Tables"]["billing_documents"]["Insert"]) {
  const { error } = await createAdminClient().from("billing_documents").insert(row);
  if (error && error.code !== "23505") throw new Error(`billing document insert failed: ${error.message}`);
}

/**
 * Ensure receipt documents exist for a succeeded payment and that their
 * statuses follow refunds. Returns the Foremint receipt (if any).
 */
export async function syncBillingDocuments(input: {
  transaction: PaymentTransactionRow;
  facts: PaymentFacts;
  product: ProductRow | null;
  plan: PlanRow | null;
}): Promise<BillingDocumentRow | null> {
  const { transaction: tx, facts, product, plan } = input;
  const everPaid = Boolean(facts.paidAt) && ["succeeded", "refunded", "partially_refunded", "disputed"].includes(tx.status);
  if (!everPaid) return null;
  const admin = createAdminClient();
  const issuedAt = facts.paidAt ? new Date(facts.paidAt) : new Date();

  // 1. Whop's own receipt (PDF generated by Whop when downloaded).
  if (!(await findDocument(tx.id, "whop", "receipt"))) {
    await insertIgnoringDuplicate({
      user_id: tx.user_id,
      transaction_id: tx.id,
      document_type: "receipt",
      issuer: "whop",
      number: `WHOP-${facts.whopPaymentId}`,
      status: "paid",
      currency: facts.currency,
      total_cents: facts.totalCents,
      issued_at: issuedAt.toISOString(),
      snapshot: { whopPaymentId: facts.whopPaymentId } as Json,
    });
  }

  // 2. Foremint-branded receipt, frozen at issue time.
  let receipt = await findDocument(tx.id, "foremint", "receipt");
  const seller = await getReceiptSeller();
  const customer = await customerFor(tx.user_id, facts);
  const productName = product?.name ?? null;
  const planName = plan?.name ?? null;
  const period = plan?.plan_type === "recurring" ? `Billed every ${billingPeriodLabel(plan.billing_period_days)}` : null;
  const lines = toReceiptLines(facts.lineItems, {
    description: productName ?? "Foremint Academy purchase",
    detail: planName,
    amountCents: facts.totalCents + facts.discountCents - (facts.taxBehavior === "exclusive" ? facts.taxCents ?? 0 : 0),
  });

  if (!receipt) {
    const number = await nextNumber("receipt", issuedAt);
    const snapshot = buildReceiptSnapshot({
      kind: "receipt",
      number,
      issuedAt,
      paidAt: facts.paidAt,
      currency: facts.currency,
      paymentStatus: "paid",
      seller,
      customer,
      productName,
      planName,
      billingPeriod: period,
      lines,
      discountCents: facts.discountCents,
      taxCents: facts.taxCents,
      taxBehavior: facts.taxBehavior,
      providerTotalCents: facts.totalCents,
      refundedCents: 0,
      promoCodeId: facts.promoCodeId,
      paymentMethod: facts.paymentMethod,
      whopPaymentId: facts.whopPaymentId,
      whopMembershipId: facts.whopMembershipId,
    });
    await insertIgnoringDuplicate({
      user_id: tx.user_id,
      transaction_id: tx.id,
      document_type: "receipt",
      issuer: "foremint",
      number,
      status: "paid",
      currency: facts.currency,
      total_cents: facts.totalCents,
      issued_at: issuedAt.toISOString(),
      snapshot: snapshot as unknown as Json,
    });
    receipt = await findDocument(tx.id, "foremint", "receipt");
  }

  // 3. Refund state: receipt status + one credit note that tracks the refunded total.
  if (facts.refundedCents > 0 && receipt) {
    const fully = facts.refundedCents >= facts.totalCents;
    const status = fully ? "refunded" : "paid";
    await admin.from("billing_documents").update({ status }).eq("transaction_id", tx.id).eq("document_type", "receipt");

    const creditIssuedAt = tx.refunded_at ? new Date(tx.refunded_at) : new Date();
    const existingNote = await findDocument(tx.id, "foremint", "credit_note");
    const noteNumber = existingNote?.number ?? (await nextNumber("credit_note", creditIssuedAt));
    const noteSnapshot = buildReceiptSnapshot({
      kind: "credit_note",
      number: noteNumber,
      issuedAt: existingNote ? new Date(existingNote.issued_at) : creditIssuedAt,
      paidAt: facts.paidAt,
      currency: facts.currency,
      paymentStatus: fully ? "refunded" : "partially_refunded",
      seller,
      customer,
      productName,
      planName,
      billingPeriod: period,
      lines,
      discountCents: facts.discountCents,
      taxCents: facts.taxCents,
      taxBehavior: facts.taxBehavior,
      providerTotalCents: facts.totalCents,
      refundedCents: facts.refundedCents,
      promoCodeId: facts.promoCodeId,
      paymentMethod: facts.paymentMethod,
      whopPaymentId: facts.whopPaymentId,
      whopMembershipId: facts.whopMembershipId,
      relatesTo: receipt.number,
    });
    if (existingNote) {
      await admin
        .from("billing_documents")
        .update({ total_cents: facts.refundedCents, snapshot: noteSnapshot as unknown as Json, status: "issued" })
        .eq("id", existingNote.id);
    } else {
      await insertIgnoringDuplicate({
        user_id: tx.user_id,
        transaction_id: tx.id,
        document_type: "credit_note",
        issuer: "foremint",
        number: noteNumber,
        status: "issued",
        currency: facts.currency,
        total_cents: facts.refundedCents,
        issued_at: creditIssuedAt.toISOString(),
        snapshot: noteSnapshot as unknown as Json,
      });
    }
  }
  return receipt;
}

export function snapshotOf(doc: BillingDocumentRow): ReceiptSnapshot | null {
  const s = doc.snapshot as unknown as ReceiptSnapshot;
  return s && s.version === 1 && Array.isArray(s.lines) ? s : null;
}
