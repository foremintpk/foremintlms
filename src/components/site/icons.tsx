import {
  Award,
  BookOpen,
  Clock,
  ClipboardCheck,
  Code,
  Compass,
  Globe,
  GraduationCap,
  Hammer,
  Landmark,
  LayoutTemplate,
  LifeBuoy,
  Lightbulb,
  Megaphone,
  MessagesSquare,
  Package,
  PlayCircle,
  Radio,
  Rocket,
  Search,
  ShieldCheck,
  ShoppingBag,
  Smartphone,
  Sparkles,
  Store,
  Tag,
  Target,
  TrendingUp,
  Users,
  type LucideIcon,
} from "lucide-react";

/** Whitelisted icons that admins can reference by name in CMS content. */
const ICONS: Record<string, LucideIcon> = {
  award: Award,
  "book-open": BookOpen,
  clock: Clock,
  "clipboard-check": ClipboardCheck,
  code: Code,
  compass: Compass,
  globe: Globe,
  "graduation-cap": GraduationCap,
  hammer: Hammer,
  landmark: Landmark,
  "layout-template": LayoutTemplate,
  "life-buoy": LifeBuoy,
  lightbulb: Lightbulb,
  megaphone: Megaphone,
  "messages-square": MessagesSquare,
  package: Package,
  "play-circle": PlayCircle,
  radio: Radio,
  rocket: Rocket,
  search: Search,
  "shield-check": ShieldCheck,
  "shopping-bag": ShoppingBag,
  smartphone: Smartphone,
  sparkles: Sparkles,
  store: Store,
  tag: Tag,
  target: Target,
  "trending-up": TrendingUp,
  users: Users,
};

export function CmsIcon({ name, className }: { name: string | null | undefined; className?: string }) {
  const Icon = (name && ICONS[name]) || Sparkles;
  return <Icon className={className} aria-hidden />;
}
