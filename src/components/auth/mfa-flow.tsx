"use client";

import { useState } from "react";
import { Copy, ShieldCheck } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { InputOTP, InputOTPGroup, InputOTPSlot } from "@/components/ui/input-otp";
import { Spinner } from "@/components/ui/spinner";
import { useAction } from "@/hooks/use-action";
import { startTotpEnrollmentAction, verifyTotpAction } from "@/app/(auth)/actions";
import { FormAlert } from "./form-bits";

function CodeForm({ factorId, enrolling, next, submitLabel }: { factorId: string; enrolling: boolean; next?: string; submitLabel: string }) {
  const [code, setCode] = useState("");
  const [navigating, setNavigating] = useState(false);
  const { run, pending, error } = useAction(verifyTotpAction, {
    silent: true,
    onSuccess: ({ redirectTo }) => {
      setNavigating(true);
      window.location.assign(redirectTo);
    },
  });
  const busy = pending || navigating;
  const submit = (value: string) => {
    if (value.length === 6 && !busy) void run({ factorId, code: value, enrolling, next });
  };

  return (
    <form
      className="grid gap-4"
      onSubmit={(e) => {
        e.preventDefault();
        submit(code);
      }}
    >
      {error ? <FormAlert>{error}</FormAlert> : null}
      <div className="grid gap-2">
        <label htmlFor="mfa-code" className="text-sm font-medium">
          6-digit code
        </label>
        <InputOTP
          id="mfa-code"
          maxLength={6}
          value={code}
          onChange={(v) => {
            const digits = v.replace(/\D/g, "");
            setCode(digits);
            if (digits.length === 6) submit(digits);
          }}
          autoFocus
          inputMode="numeric"
          autoComplete="one-time-code"
          aria-label="6-digit code from your authenticator app"
        >
          <InputOTPGroup>
            {[0, 1, 2, 3, 4, 5].map((i) => (
              <InputOTPSlot key={i} index={i} className="size-12 text-lg" />
            ))}
          </InputOTPGroup>
        </InputOTP>
      </div>
      <Button type="submit" className="h-11 w-full" disabled={busy || code.length !== 6}>
        {busy ? (
          <>
            <Spinner className="size-4" /> Verifying…
          </>
        ) : (
          submitLabel
        )}
      </Button>
    </form>
  );
}

/** Verify with an existing authenticator factor. */
export function MfaChallenge({ factorId, next }: { factorId: string; next?: string }) {
  return <CodeForm factorId={factorId} enrolling={false} next={next} submitLabel="Verify and continue" />;
}

/** Set up a new authenticator app, then verify the first code. */
export function MfaEnroll({ next }: { next?: string }) {
  const [enrollment, setEnrollment] = useState<{ factorId: string; qrCode: string; secret: string } | null>(null);
  const { run, pending, error } = useAction(startTotpEnrollmentAction, { silent: true, onSuccess: setEnrollment });

  if (!enrollment) {
    return (
      <div className="grid gap-4">
        {error ? <FormAlert>{error}</FormAlert> : null}
        <ol className="grid gap-3 text-sm text-muted-foreground">
          <li className="flex gap-3">
            <span className="grid size-6 shrink-0 place-items-center rounded-full bg-brand-soft text-xs font-semibold text-primary">1</span>
            Install an authenticator app such as Google Authenticator, Microsoft Authenticator, 1Password or Authy.
          </li>
          <li className="flex gap-3">
            <span className="grid size-6 shrink-0 place-items-center rounded-full bg-brand-soft text-xs font-semibold text-primary">2</span>
            Scan the QR code we show you next.
          </li>
          <li className="flex gap-3">
            <span className="grid size-6 shrink-0 place-items-center rounded-full bg-brand-soft text-xs font-semibold text-primary">3</span>
            Enter the 6-digit code the app shows to finish.
          </li>
        </ol>
        <Button type="button" className="h-11 w-full" disabled={pending} onClick={() => run(undefined)}>
          {pending ? (
            <>
              <Spinner className="size-4" /> Preparing…
            </>
          ) : (
            <>
              <ShieldCheck className="size-4" /> Set up authenticator app
            </>
          )}
        </Button>
      </div>
    );
  }

  return (
    <div className="grid gap-5">
      <div className="grid justify-items-center gap-3 rounded-2xl border bg-white p-5 shadow-card">
        {/* QR is an SVG data URI generated by Supabase Auth. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={enrollment.qrCode} alt="QR code for your authenticator app" width={184} height={184} className="size-46" />
        <p className="text-center text-xs text-[#615d80]">Scan with your authenticator app</p>
      </div>
      <div className="grid gap-1.5">
        <p className="text-sm font-medium">Can&rsquo;t scan? Enter this key instead</p>
        <div className="flex items-center gap-2 rounded-lg border bg-muted/50 px-3 py-2">
          <code className="min-w-0 flex-1 truncate font-mono text-sm">{enrollment.secret}</code>
          <Button
            type="button"
            variant="ghost"
            size="icon-sm"
            aria-label="Copy setup key"
            onClick={() => {
              void navigator.clipboard.writeText(enrollment.secret).then(() => toast.success("Setup key copied"));
            }}
          >
            <Copy className="size-4" />
          </Button>
        </div>
      </div>
      <CodeForm factorId={enrollment.factorId} enrolling next={next} submitLabel="Verify and turn on" />
    </div>
  );
}
